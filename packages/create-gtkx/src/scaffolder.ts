import * as p from "@clack/prompts";
import { isValidApplicationId } from "@gtkx/config/internal";
import { errorMessage, packageVersion, upperFirst } from "@gtkx/utils";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { addDependency, detectPackageManager as nypmDetectPackageManager } from "nypm";
import { x } from "tinyexec";
import { OperationCanceledError, ScaffoldAbortedError } from "./errors.js";
import { isKnownPackageManager, PACKAGE_MANAGERS, type PackageManager } from "./package-managers.js";
import { isValidProjectName } from "./project-name.js";
import { listTemplates, renderFile, type TemplateContext } from "./templates.js";

type CreateOptions = {
    name?: string | undefined;
    applicationId?: string | undefined;
    packageManager?: PackageManager | undefined;
    typescript?: boolean | undefined;
    includeTesting?: boolean | undefined;
    interactive?: boolean | undefined;
    overwrite?: boolean | undefined;
};

type ResolvedOptions = {
    target: string;
    name: string;
    applicationId: string;
    packageManager: PackageManager;
    typescript: boolean;
    includeTesting: boolean;
};

type InstallDependenciesOptions = {
    cwd: string;
    packageManager: PackageManager;
    dependencies: string[];
    dev: boolean;
};

type InstallAllOptions = {
    root: string;
    target: string;
    packageManager: PackageManager;
    devDependencies: string[];
};

const selfVersion = packageVersion(import.meta.url);

const GTKX_ENV_MODULE_HEADER = `/**
 * Generated by \`gtkx codegen\`, \`gtkx dev\`, and \`gtkx build\`; do not edit.
 */`;

const DEPENDENCIES = ["@gtkx/css", "@gtkx/runtime", "@gtkx/react", "react"];
const DEV_DEPENDENCIES = ["@gtkx/cli", "@gtkx/config", "vite"];
const TYPESCRIPT_DEV_DEPENDENCIES = ["@types/node", "@types/react", "typescript"];
const TESTING_DEV_DEPENDENCIES = ["@gtkx/testing", "vitest"];

const DEV_COMMAND: Record<PackageManager, string> = Object.fromEntries(
    PACKAGE_MANAGERS.map((manager) => [manager.value, manager.devCommand]),
) as Record<PackageManager, string>;

const INSTALL_COMMAND: Record<PackageManager, string> = Object.fromEntries(
    PACKAGE_MANAGERS.map((manager) => [manager.value, manager.installCommand]),
) as Record<PackageManager, string>;

const TESTING_TEMPLATES = new Set(["vitest.config.ts", "tests/app.test.tsx"]);
const TYPESCRIPT_TEMPLATES = new Set(["tsconfig.json", "src/gtkx-env.d.ts"]);
const PACKAGE_JSON_TEMPLATE = "package.json";

const HEADLESS_COMPOSITOR_NOTE = `

To run tests, you need a headless Wayland compositor installed:
  Fedora: sudo dnf install sway
  Ubuntu: sudo apt install sway`;

const pinGtkxDependency = (name: string, version: string): string =>
    name.startsWith("@gtkx/") ? `${name}@^${version}` : name;

const getDevCommand = (packageManager: PackageManager): string => DEV_COMMAND[packageManager];
const getInstallCommand = (packageManager: PackageManager): string => INSTALL_COMMAND[packageManager];
const titleFromName = (name: string): string => name.split("-").map((part) => upperFirst(part)).join(" ");
const suggestApplicationId = (name: string): string => `com.${name.replaceAll("-", "")}.app`;

const stripTrailingSlashes = (value: string): string => {
    let end = value.length;

    while (end > 0 && value[end - 1] === "/") {
        end--;
    }

    return value.slice(0, end);
};

const formatTargetDir = (target: string): string => stripTrailingSlashes(target.trim().replaceAll(/[<>:"\\|?*]/g, ""));
const deriveProjectName = (target: string): string => basename(resolve(process.cwd(), target));

const isDirEmpty = (dir: string): boolean => {
    const entries = readdirSync(dir);

    return entries.length === 0 || (entries.length === 1 && entries[0] === ".git");
};

const getDevDependencies = ({
    typescript,
    includeTesting,
}: Pick<ResolvedOptions, "typescript" | "includeTesting">): string[] => {
    const devDeps = [...DEV_DEPENDENCIES];

    if (typescript) {
        devDeps.push(...TYPESCRIPT_DEV_DEPENDENCIES);
    }

    if (includeTesting) {
        devDeps.push(...TESTING_DEV_DEPENDENCIES);
    }

    return devDeps;
};

const guardCancellation = <T>(value: T | symbol): T => {
    if (p.isCancel(value)) {
        p.cancel("Operation canceled");
        throw new OperationCanceledError();
    }

    return value;
};

const validateProjectName = (value: string | undefined): string | undefined => {
    if (!value) {
        return "Project name is required";
    }

    if (!isValidProjectName(value)) {
        return "Project name must be lowercase letters, numbers, and hyphens only";
    }

    return undefined;
};

const validateApplicationIdInput = (value: string | undefined): string | undefined => {
    if (!value) {
        return "Application ID is required";
    }

    if (!isValidApplicationId(value)) {
        return "Application ID must be reverse domain notation (e.g., com.example.myapp)";
    }

    return undefined;
};

const fail = (message: string): never => {
    p.log.error(message);
    throw new ScaffoldAbortedError(message);
};

const validateTarget = (value: string | undefined): string | undefined => {
    if (!value) {
        return "Project directory is required";
    }

    return validateProjectName(deriveProjectName(formatTargetDir(value)));
};

const promptTarget = async (): Promise<string> =>
    guardCancellation(
        await p.text({
            message: "Project directory",
            placeholder: "my-app",
            validate: validateTarget,
        }),
    );

const promptApplicationId = async (name: string): Promise<string> => {
    const defaultApplicationId = suggestApplicationId(name);

    return guardCancellation(
        await p.text({
            message: "Application ID",
            placeholder: defaultApplicationId,
            initialValue: defaultApplicationId,
            validate: validateApplicationIdInput,
        }),
    );
};

const detectPackageManager = async (cwd: string): Promise<PackageManager | undefined> => {
    const detected = await nypmDetectPackageManager(cwd, { includeParentDirs: true });

    if (!detected) {
        return undefined;
    }

    return isKnownPackageManager(detected.name) ? detected.name : undefined;
};

const packageManagerHint = (
    manager: (typeof PACKAGE_MANAGERS)[number],
    detected: PackageManager | undefined,
): string | undefined => {
    if (detected === manager.value) {
        return "detected";
    }

    if (manager.recommended) {
        return "recommended";
    }

    return undefined;
};

const packageManagerOption = (manager: (typeof PACKAGE_MANAGERS)[number], detected: PackageManager | undefined) => {
    const hint = packageManagerHint(manager, detected);

    return { value: manager.value, label: manager.label, ...(hint !== undefined && { hint }) };
};

const detectedPackageManager = async (): Promise<PackageManager | undefined> => {
    try {
        return await detectPackageManager(process.cwd());
    } catch {
        return undefined;
    }
};

const promptPackageManager = async (): Promise<PackageManager> => {
    const detected = await detectedPackageManager();
    const initial: PackageManager = detected ?? "pnpm";

    return guardCancellation(
        await p.select<PackageManager>({
            message: "Package manager",
            options: PACKAGE_MANAGERS.map((manager) => packageManagerOption(manager, detected)),
            initialValue: initial,
        }),
    );
};

const promptTypeScript = async (): Promise<boolean> =>
    guardCancellation(
        await p.confirm({
            message: "Use TypeScript?",
            initialValue: true,
        }),
    );

const promptTesting = async (): Promise<boolean> =>
    guardCancellation(
        await p.confirm({
            message: "Include testing setup (Vitest)?",
            initialValue: true,
        }),
    );

const emptyDir = (root: string): void => {
    for (const entry of readdirSync(root)) {
        if (entry === ".git") {
            continue;
        }

        rmSync(join(root, entry), { recursive: true, force: true });
    }
};

const validateResolvedOptions = (name: string, applicationId: string): void => {
    const nameError = validateProjectName(name);

    if (nameError) {
        fail(nameError);
    }

    const applicationIdError = validateApplicationIdInput(applicationId);

    if (applicationIdError) {
        fail(applicationIdError);
    }
};

const confirmOverwrite = async (target: string, options: CreateOptions): Promise<boolean> => {
    if (!options.interactive) {
        return options.overwrite === true;
    }

    return guardCancellation(
        await p.confirm({
            message: `Directory "${target}" is not empty. Overwrite its contents?`,
            initialValue: false,
        }),
    );
};

const handleTargetDirectory = async (root: string, target: string, options: CreateOptions): Promise<void> => {
    if (!existsSync(root) || isDirEmpty(root)) {
        return;
    }

    if (await confirmOverwrite(target, options)) {
        emptyDir(root);

        return;
    }

    fail(`Directory "${target}" is not empty`);
};

const resolveTarget = async (options: CreateOptions): Promise<string> => {
    if (options.name !== undefined) {
        return formatTargetDir(options.name);
    }

    if (!options.interactive) {
        return fail("Project directory is required");
    }

    return formatTargetDir(await promptTarget());
};

const resolveApplicationId = async (options: CreateOptions, name: string): Promise<string> => {
    if (options.applicationId !== undefined) {
        return options.applicationId;
    }

    return options.interactive ? promptApplicationId(name) : suggestApplicationId(name);
};

const resolvePackageManager = async (options: CreateOptions): Promise<PackageManager> => {
    if (options.packageManager !== undefined) {
        return options.packageManager;
    }

    if (options.interactive) {
        return promptPackageManager();
    }

    return (await detectedPackageManager()) ?? "pnpm";
};

const resolveTypeScript = async (options: CreateOptions): Promise<boolean> => {
    if (options.typescript !== undefined) {
        return options.typescript;
    }

    return options.interactive ? promptTypeScript() : true;
};

const resolveIncludeTesting = async (options: CreateOptions): Promise<boolean> => {
    if (options.includeTesting !== undefined) {
        return options.includeTesting;
    }

    return options.interactive ? promptTesting() : true;
};

const resolveOptions = async (options: CreateOptions): Promise<ResolvedOptions> => {
    const target = await resolveTarget(options);
    const name = deriveProjectName(target);
    const applicationId = await resolveApplicationId(options, name);
    validateResolvedOptions(name, applicationId);
    const root = resolve(process.cwd(), target);
    await handleTargetDirectory(root, target, options);
    const packageManager = await resolvePackageManager(options);
    const isTypescript = await resolveTypeScript(options);
    const isIncludeTesting = await resolveIncludeTesting(options);

    return { target, name, applicationId, packageManager, typescript: isTypescript, includeTesting: isIncludeTesting };
};

const isTemplateIncluded = (templateRelativePath: string, resolved: ResolvedOptions): boolean => {
    if (TESTING_TEMPLATES.has(templateRelativePath)) {
        return resolved.includeTesting;
    }

    if (TYPESCRIPT_TEMPLATES.has(templateRelativePath)) {
        return resolved.typescript;
    }

    return true;
};

const toDestinationPath = (templateRelativePath: string, isTypescript: boolean): string =>
    isTypescript ? templateRelativePath : templateRelativePath.replace(/\.tsx$/, ".jsx").replace(/\.ts$/, ".js");

const addTestScript = (root: string): void => {
    const packageJsonPath = join(root, PACKAGE_JSON_TEMPLATE);

    const manifest = JSON.parse(readFileSync(packageJsonPath, "utf8")) as {
        scripts: Record<string, string>;
    };

    manifest.scripts.test = "vitest";
    writeFileSync(packageJsonPath, `${JSON.stringify(manifest, null, 4)}\n`);
};

const scaffoldProject = async (root: string, resolved: ResolvedOptions): Promise<void> => {
    const { name, applicationId, typescript, includeTesting } = resolved;

    const context: TemplateContext = {
        name,
        applicationId,
        title: titleFromName(name),
        includeTesting,
        typescript,
        importExtension: typescript ? ".js" : ".jsx",
    };

    mkdirSync(root, { recursive: true });

    for (const template of listTemplates()) {
        if (!isTemplateIncluded(template, resolved)) {
            continue;
        }

        const destination = join(root, toDestinationPath(template, typescript));
        mkdirSync(dirname(destination), { recursive: true });
        writeFileSync(destination, await renderFile(template, context));
    }

    if (includeTesting) {
        addTestScript(root);
    }
};

const installDependencies = async (options: InstallDependenciesOptions): Promise<void> => {
    const { cwd, packageManager, dependencies, dev } = options;
    await addDependency(dependencies, { cwd, packageManager, dev, silent: true });
};

const pin = (names: string[]): string[] => names.map((dependency) => pinGtkxDependency(dependency, selfVersion));

const installAllDependencies = async (options: InstallAllOptions): Promise<void> => {
    const { root, target, packageManager, devDependencies } = options;
    const spinner = p.spinner();
    spinner.start("Installing dependencies...");

    try {
        await installDependencies({ cwd: root, packageManager, dependencies: pin(DEPENDENCIES), dev: false });
        await installDependencies({ cwd: root, packageManager, dependencies: pin(devDependencies), dev: true });
        spinner.stop("Dependencies installed");
    } catch (error) {
        spinner.stop("Failed to install dependencies");
        p.log.error(`Failed to install dependencies: ${errorMessage(error)}`);
        p.log.info(`Install them manually by running:\n  cd ${target}\n  ${getInstallCommand(packageManager)}`);
        throw new ScaffoldAbortedError("Failed to install dependencies");
    }
};

const writeInitialEnvModule = (root: string): void => {
    const storeDir = join(root, "node_modules", ".gtkx");
    mkdirSync(storeDir, { recursive: true });
    writeFileSync(join(storeDir, "env.d.ts"), `${GTKX_ENV_MODULE_HEADER}\n`);
};

const initializeGitRepo = async (root: string): Promise<void> => {
    const spinner = p.spinner();
    spinner.start("Initializing git repository...");

    try {
        const opts = { nodeOptions: { cwd: root }, throwOnError: true } as const;
        await x("git", ["init"], opts);
        await x("git", ["add", "-A"], opts);
        await x("git", ["commit", "-m", "Initial commit"], opts);
        spinner.stop("Git repository initialized");
    } catch {
        spinner.stop("Failed to initialize git repository");
    }
};

const printNextSteps = (resolved: ResolvedOptions): void => {
    const devCmd = getDevCommand(resolved.packageManager);
    const cdStep = resolved.target === "." ? "" : `cd ${resolved.target}\n`;
    const testingNote = resolved.includeTesting ? HEADLESS_COMPOSITOR_NOTE : "";
    p.note(`${cdStep}${devCmd}${testingNote}`, "Next steps");
};

const scaffold = async (options: CreateOptions = {}): Promise<void> => {
    p.intro("Create GTKX App");
    const resolved = await resolveOptions(options);
    const root = resolve(process.cwd(), resolved.target);
    const devDeps = getDevDependencies(resolved);
    const projectSpinner = p.spinner();
    projectSpinner.start("Creating project structure...");
    await scaffoldProject(root, resolved);
    projectSpinner.stop("Project structure created");

    await installAllDependencies({
        root,
        target: resolved.target,
        packageManager: resolved.packageManager,
        devDependencies: devDeps,
    });

    if (resolved.typescript) {
        writeInitialEnvModule(root);
    }

    await initializeGitRepo(root);
    printNextSteps(resolved);
};

export { scaffold, type CreateOptions };

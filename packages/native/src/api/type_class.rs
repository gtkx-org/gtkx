use glib::gobject_ffi;
use glib::translate::IntoGlib as _;
use napi::bindgen_prelude::*;
use napi_derive::napi;

use crate::api::vtable::query_type;
use crate::api::{native_result, type_from_bigint};
use crate::handle::Handle;

pub(crate) fn validate_class_type(type_: glib::Type, label: &str) -> anyhow::Result<()> {
    let is_classed = unsafe {
        gobject_ffi::g_type_test_flags(type_.into_glib(), gobject_ffi::G_TYPE_FLAG_CLASSED)
    } != 0;
    anyhow::ensure!(
        is_classed,
        "{label}: type '{}' is not classed",
        type_.name()
    );
    Ok(())
}

pub(crate) fn class_pointer(type_: glib::Type, label: &str) -> anyhow::Result<Handle> {
    validate_class_type(type_, label)?;
    let class_ptr = unsafe { gobject_ffi::g_type_class_ref(type_.into_glib()) };
    anyhow::ensure!(
        !class_ptr.is_null(),
        "{label}: type '{}' has no class structure",
        type_.name()
    );

    let owner = Handle::owned_struct_with_free_fn(class_ptr, Some(gobject_ffi::g_type_class_unref));
    let query = query_type(type_).ok_or_else(|| {
        anyhow::anyhow!(
            "{label}: type '{}' has no reported class size",
            type_.name()
        )
    })?;
    Ok(Handle::pointer(class_ptr, &owner).with_allocated_bytes(query.class_size as usize))
}

/// Selects an implemented interface vtable or supplies its generated byte size.
#[napi(object, object_to_js = false)]
pub struct TypeClassOptions {
    pub interface_type: Option<BigInt>,
    pub vtable_size: Option<u32>,
}

fn interface_pointer(
    type_: glib::Type,
    interface_type: Option<glib::Type>,
    vtable_size: Option<u32>,
) -> anyhow::Result<Handle> {
    let size = vtable_size
        .ok_or_else(|| anyhow::anyhow!("An interface vtable requires its generated byte size"))?;
    anyhow::ensure!(
        size as usize >= size_of::<gobject_ffi::GTypeInterface>(),
        "An interface vtable is smaller than GTypeInterface"
    );
    let interface = interface_type.unwrap_or(type_);
    anyhow::ensure!(
        interface.is_a(glib::Type::INTERFACE),
        "The requested type is not an interface"
    );
    if interface_type.is_some() {
        let class = class_pointer(type_, "get_type_class")?;
        let pointer =
            unsafe { gobject_ffi::g_type_interface_peek(class.as_ptr(), interface.into_glib()) };
        anyhow::ensure!(
            !pointer.is_null(),
            "Type '{}' does not implement interface '{}'",
            type_.name(),
            interface.name()
        );
        return Ok(Handle::pointer(pointer, &class).with_allocated_bytes(size as usize));
    }
    let pointer = unsafe { gobject_ffi::g_type_default_interface_ref(interface.into_glib()) };
    anyhow::ensure!(
        !pointer.is_null(),
        "Interface '{}' has no default vtable",
        interface.name()
    );
    let owner = Handle::owned_struct_with_free_fn(
        pointer,
        Some(gobject_ffi::g_type_default_interface_unref),
    );
    Ok(Handle::pointer(pointer, &owner).with_allocated_bytes(size as usize))
}

/// Returns an owned reference to the class struct of `gtype`, bounded by the queried class size.
/// Dependent field and function handles retain the class reference.
#[allow(clippy::needless_pass_by_value)]
#[napi(catch_unwind)]
pub fn get_type_class(
    gtype: BigInt,
    options: Option<TypeClassOptions>,
) -> Result<External<Handle>> {
    let type_ = type_from_bigint(&gtype, "get_type_class")?;
    let interface_type = options
        .as_ref()
        .and_then(|options| options.interface_type.as_ref())
        .map(|type_| type_from_bigint(type_, "get_type_class: interface"))
        .transpose()?;
    let handle = native_result(
        "get_type_class",
        if interface_type.is_some() || type_.is_a(glib::Type::INTERFACE) {
            interface_pointer(
                type_,
                interface_type,
                options.and_then(|options| options.vtable_size),
            )
        } else {
            class_pointer(type_, "get_type_class")
        },
    )?;
    let size_hint = handle.size_hint();

    Ok(External::new_with_size_hint(handle, size_hint))
}
